SEED_YEARS = (2026, 2027)


def holidays_for_year(year: int) -> list[tuple[date, str]]:
    rows: list[tuple[date, str]] = []
    for month, day, name in (*OFFICIAL_RU, *CONTENT_RU):
        rows.append((date(year, month, day), name))
    return rows
